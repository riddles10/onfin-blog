/**
 * Generate `lib/imported-posts.ts` from the Tilda export.
 *
 * Same parser as the live Supabase import — this script just writes the
 * parsed posts to a TypeScript fixture instead of inserting into the DB,
 * so the demo path can render the real archive without infrastructure.
 *
 * Run with `npx tsx scripts/build-fixture.ts` (or via the repo's npm
 * script). Idempotent: safe to re-run any time the export changes.
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import { parseAllTildaPages } from '../lib/tilda-parse'

const EXPORT_DIR = path.resolve(process.cwd(), '_tilda_export')
const OUT_FILE = path.resolve(process.cwd(), 'lib/imported-posts.ts')

async function main() {
  const stats = await parseAllTildaPages(EXPORT_DIR)
  console.log(`Found ${stats.total} news_* candidates`)
  console.log(`  · ${stats.promosSkipped} skipped as promo`)
  console.log(`  · ${stats.shortSkipped} skipped as too short`)
  console.log(`  · ${stats.parsed} parsed for fixture`)

  const header = `// AUTO-GENERATED by scripts/build-fixture.ts. Do not edit by hand —
// run \`npx tsx scripts/build-fixture.ts\` to regenerate.
//
// Source: \`_tilda_export/\`. Parsed with \`lib/tilda-parse.ts\` so the
// demo-mode path renders the same posts the live Supabase import would
// produce, end to end.

import type { DemoPost } from '@/lib/demo-data'
`

  // Stringify each post as an object literal. Use JSON.stringify so the
  // body's HTML (which contains backticks, single + double quotes, and
  // unicode em-dashes) escapes safely without us hand-escaping anything.
  const lines: string[] = []
  lines.push(header)
  lines.push(`export const IMPORTED_POSTS: DemoPost[] = [`)
  for (const post of stats.posts) {
    lines.push(`  {`)
    lines.push(`    id: ${JSON.stringify(`tilda-${post.slug}`)},`)
    lines.push(`    slug: ${JSON.stringify(post.slug)},`)
    lines.push(`    title_en: ${JSON.stringify(post.title)},`)
    lines.push(`    excerpt_en: ${JSON.stringify(post.excerpt)},`)
    lines.push(`    body_en: ${JSON.stringify(post.body)},`)
    lines.push(`    category: ${JSON.stringify(post.category)},`)
    lines.push(`    cover_image: ${JSON.stringify(post.coverImage)},`)
    lines.push(`    published_at: ${JSON.stringify(post.publishedAt)},`)
    lines.push(`    blog_author_id: 'demo-author',`)
    lines.push(`  },`)
  }
  lines.push(`]`)
  lines.push('')

  await fs.writeFile(OUT_FILE, lines.join('\n'), 'utf8')
  console.log(`\nWrote ${OUT_FILE} (${stats.posts.length} posts)`)
}

main().catch((err) => {
  console.error('Fixture build failed:', err)
  process.exit(1)
})
